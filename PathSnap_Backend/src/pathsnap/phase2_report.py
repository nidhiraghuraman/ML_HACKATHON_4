"""Writes results/phase2/phase2_report.md. Every number is taken from the computed results."""
from __future__ import annotations
from pathlib import Path
import numpy as np
import pandas as pd

from .features import FEATURE_SCHEMA


def _pct(x):
    return f"{100 * x:.2f}%"


def write_report(out: Path, cfg, all_obs, all_cand, rep, lq, warnings, cov, actual_cov, fstats, auc, corr,
                 checks, meta, plots, maps):
    p2 = cfg["phase2"]
    pre, cc, lc = p2["preprocessing"], p2["candidates"], p2["labels"]
    L = ["# PathSnap — Phase 2 Report: Candidates, Features and Labels", "",
         "_Generated by `scripts/build_phase2_dataset.py`. All numbers are computed from the real data in this run._", "",
         f"Run time {meta['elapsed_s']:.0f} s, peak memory {meta['peak_rss_mb']:.0f} MB, Python {meta['python']}.", ""]

    # ------------------------------------------------------------------ 1 overview
    L += ["## 1. Overview", "", "| Partition | Trips | GPS points | Candidate rows | Aligned | Ambiguous | Unalignable | Coverage* |",
          "|---|---|---|---|---|---|---|---|"]
    for part, o in all_obs.items():
        st = o.obs_status.value_counts()
        L.append(f"| {part} | {o.trip_id.nunique()} | {len(o):,} | {len(all_cand[part]):,} | {st.get('aligned', 0):,} | "
                 f"{st.get('ambiguous', 0):,} | {st.get('unalignable', 0):,} | {_pct(actual_cov[part]['coverage'])} |")
    L += ["", "*Coverage = share of alignable GPS points (aligned + ambiguous) whose aligned route arc is among the generated candidates.",
          "The student-test partition is processed with the identical pipeline but saved separately; its labels are for evaluation only.", ""]

    # ------------------------------------------------------------------ 2 preprocessing
    o_all = pd.concat(all_obs.values(), ignore_index=True)
    L += ["## 2. Preprocessing", "",
          "**Projection.** Each trip is converted to metres in the UTM zone of its median GPS point (`geo.LocalProjector`, pyproj). "
          "UTM is a conformal projection whose distance error inside a zone is below about 0.1%; trips here span at most ~100 km, so "
          "straight-line distances in metres are accurate for 5-50 m GPS-to-road distances. Limitation: a trip far outside its zone's "
          "central meridian has slightly larger scale error; Phase 1 measured a maximum 0.55% step-length difference against haversine. "
          "Headings are measured in the same grid for GPS and roads, so the grid-north offset cancels in heading differences.", "",
          "**Nothing is deleted.** Every .track row becomes one observation (`obs_idx` = original row). Problem points are flagged:", "",
          "| Flag | Rule (config) | Points | Share |", "|---|---|---|---|",
          f"| is_stationary | stay-point: all points within {pre['stationary_max_disp_m']} m of the stay's first point for >= {pre['stationary_window_s']} s | {int(o_all.is_stationary.sum()):,} | {_pct(o_all.is_stationary.mean())} |",
          f"| gap_before | previous point > {pre['gap_s']} s earlier | {int(o_all.gap_before.sum()):,} | {_pct(o_all.gap_before.mean())} |",
          f"| long gap (new segment_id) | previous point > {pre['long_gap_s']} s earlier | {int((o_all.dt_prev_s > pre['long_gap_s']).sum()):,} | {_pct((o_all.dt_prev_s > pre['long_gap_s']).mean())} |",
          f"| is_spike | in and out speed > {pre['spike_speed_mps']} m/s | {int(o_all.is_spike.sum()):,} | {_pct(o_all.is_spike.mean())} |",
          f"| bearing_valid | moved >= {pre['bearing_min_disp_m']} m between t-{pre['bearing_half_window_s']} s and t+{pre['bearing_half_window_s']} s | {int(o_all.bearing_valid.sum()):,} | {_pct(o_all.bearing_valid.mean())} |",
          "", f"Trips whose timestamps needed re-sorting: {int(rep.pre_reordered.sum())}. Duplicate timestamps: {int(rep.pre_duplicate_timestamps.sum())}.", ""]

    # ------------------------------------------------------------------ 3 road geometry
    L += ["## 3. Road geometry", "",
          "Each arc becomes a straight directed segment from its from-node to its to-node, keeping `arc_id`, `from_node`, `to_node`, "
          "length and heading. Arcs with a missing node reference or zero length are counted and kept out of the spatial index.", "",
          f"- Arcs processed: {int(rep.net_n_arcs.sum()):,}; indexed: {int(rep.net_indexed_arcs.sum()):,}.",
          f"- Invalid node references: {int(rep.net_invalid_node_ref.sum())}; zero-length arcs: {int(rep.net_zero_length.sum()):,} "
          f"(self-loops {int(rep.net_self_loops.sum())}); duplicate (same from/to) arcs: {int(rep.net_duplicate_arcs.sum()):,}.",
          f"- Share of arcs with a reverse twin: median {rep.net_twin_frac.median():.1%} per trip.", ""]

    # ------------------------------------------------------------------ 4 candidates
    tr = "train" if "train" in all_obs else next(iter(all_obs))
    ot = all_obs[tr]
    nc = ot.n_candidates
    L += ["## 4. Candidate generation", "",
          "Method: shapely `STRtree` (an R-tree spatial index) per trip. Each GPS point is queried with `dwithin` at the first radius; "
          f"points with fewer than {cc['min_candidates']} arcs are re-queried at the next radius ({cc['radii_m']} m). Exact point-to-segment "
          f"distances are computed with numpy, candidates are ranked by distance (ties broken by arc_id) and the nearest {cc['max_candidates']} are kept. "
          "The index avoids comparing each point with every arc.", "",
          f"**{tr} partition:** {len(ot):,} points, {len(all_cand[tr]):,} candidate rows; candidates per point mean {nc.mean():.2f}, "
          f"median {nc.median():.0f}, min {nc.min()}, max {nc.max()}. Zero candidates: {int((nc == 0).sum())} points ({_pct((nc == 0).mean())}). "
          f"Radius expanded: {int(ot.radius_expanded.sum()):,} points ({_pct(ot.radius_expanded.mean())}).", "",
          "### Coverage study (why these radii and K)", "",
          "For every alignable training point we computed the exact distance to its aligned arc and that arc's rank among ALL arcs of the trip. "
          "The table shows the share that would be covered with a fixed radius and top-K (no expansion):", ""]
    c = cov[cov.partition == tr]
    ks = [str(k) for k in p2["diagnostics"]["coverage_k"] if k in (2, 4, 8, 12, 16, 24, 32)] + ["all"]
    radii = [r for r in p2["diagnostics"]["coverage_radii_m"] if r in (15, 25, 50, 100, 200)]
    L.append("| radius \\ K | " + " | ".join(ks) + " |")
    L.append("|---" * (len(ks) + 1) + "|")
    for r in radii:
        row = [f"{c[(c.radius_m == r) & (c.k.astype(str) == k)].coverage.iat[0] * 100:.2f}" for k in ks]
        L.append(f"| {r} m | " + " | ".join(row) + " |")
    r50 = c[c.radius_m == 50]
    kline = ", ".join(f"K={k}: {r50[r50.k.astype(str) == str(k)].coverage.iat[0] * 100:.2f}%" for k in (8, 16, 24, 32) if str(k) in set(r50.k.astype(str)))
    ex = ot[ot.radius_expanded]
    zero50 = len(ex)
    ex_unal = float((ex.obs_status == "unalignable").mean()) if zero50 else 0.0
    ex_top = ex.trip_id.value_counts()
    ex_top_txt = f"{ex_top.iat[0]:,} of them from trip {ex_top.index[0]}" if zero50 else "none"
    L += ["", f"**Choice.** At 50 m: {kline}. Coverage stops improving beyond 50 m because points farther than "
          f"{lc['unalign_dist_m']} m from their aligned arc are `unalignable` by definition. The configuration uses K = {cc['max_candidates']}. "
          f"The larger radii are a fallback so that points with fewer than {cc['min_candidates']} arcs within {cc['radii_m'][0]} m still "
          f"receive candidates at inference time. {zero50:,} training points used them; their nearest arc is at a median "
          f"{ex.nearest_dist_m.median():.0f} m, {ex_unal:.1%} of them are unalignable, and {ex_top_txt} (parked away from roads).", "",
          "Actual pipeline coverage (with expansion), by top-K cut-off:", "", "| Partition | " +
          " | ".join(f"top-{k}" for k in actual_cov[tr]["topk"]) + " | missing (points) |",
          "|---" * (len(actual_cov[tr]["topk"]) + 2) + "|"]
    for part, a in actual_cov.items():
        L.append(f"| {part} | " + " | ".join(f"{v * 100:.2f}%" for v in a["topk"].values()) + f" | {a['missing']:,} of {a['alignable']:,} |")
    L += ["", f"Runtime: total {rep.total_s.sum():.0f} s for {len(rep)} trips (median {rep.total_s.median():.2f} s, max {rep.total_s.max():.2f} s "
          f"for trip {rep.loc[rep.total_s.idxmax(), 'trip_id']}). Candidate search alone: {rep.candidates_s.sum():.1f} s in total. "
          f"Peak process memory: {meta['peak_rss_mb']:.0f} MB.", ""]

    # ------------------------------------------------------------------ 5 features
    L += ["## 5. Features", "", "Full schema: `feature_schema.json`. Statistics: `feature_stats_train.csv`.", "",
          "| Feature | Unit | Level | Missing (train) | Single-feature AUC | Meaning |", "|---|---|---|---|---|---|"]
    a = auc.set_index("feature")
    fs = fstats.set_index("feature")
    for f, (unit, lvl, _, desc) in FEATURE_SCHEMA.items():
        av = a.loc[f, "auc"] if f in a.index and pd.notna(a.loc[f, "auc"]) else np.nan
        L.append(f"| `{f}` | {unit} | {lvl} | {_pct(fs.loc[f, 'missing_frac'])} | {'n/a' if np.isnan(av) else f'{av:.3f}'} | {desc} |")
    pairs = []
    cols = corr.columns
    for i in range(len(cols)):
        for j in range(i + 1, len(cols)):
            v = corr.iat[i, j]
            if np.isfinite(v) and abs(v) >= 0.9:
                pairs.append(f"`{cols[i]}`-`{cols[j]}` ({v:+.2f})")
    L += ["", "AUC is the ranking power of the feature on its own for positive (1) vs negative (0) candidates: 0.5 = none; "
          "values below 0.5 mean lower values indicate positives. Observation-level features have the same value for all candidates "
          "of a point, so they cannot rank candidates within a point; their AUC only reflects how the share of positives differs between "
          "points (e.g. a point with many candidates has a smaller positive share, which is why `n_candidates` is far from 0.5). They are "
          "kept because they change how much to trust the candidate-level features (e.g. heading is meaningless when stationary). "
          "`arc_length_m` scoring high means positives tend to be longer arcs (main roads): a real pattern in this data, but one that may "
          "not hold in every city.", "",
          f"Infinite values: {int(fstats.infinite.sum())}. Feature pairs with |Spearman| >= 0.9: {', '.join(pairs) if pairs else 'none'}.", ""]

    # ------------------------------------------------------------------ 6 labels
    L += ["## 6. Labels: aligning GPS points with the reference route", "",
          "**1. Why this method.** Route rows and GPS rows are not aligned, a route can revisit arcs, and GPS points can be far "
          "from the route. Labelling each point with its nearest route arc ignores travel order, so on a road driven in both "
          "directions, or passed twice, it can pick the wrong pass. An order-preserving alignment uses the one piece of information "
          "the route really gives: the order of travel.", "",
          "**2. How it works.** States are route positions (row numbers of .route). Each GPS point gets one position; positions never "
          "decrease over time but may skip. The cost of assigning point i to position j is "
          f"min(d, {lc['cap_m']} m)^2 / (2*{lc['sigma_m']}^2) + {lc['w_heading']} * (1 - cos heading difference)/2 (heading term only when moving), "
          f"plus {lc['eta_per_m']} per metre advanced along the route. Dynamic programming with a running minimum finds the exact "
          "lowest-cost assignment in O(points x route arcs).", "",
          "**3. Assumptions.** The route is listed in travel order; the vehicle does not move backwards along it; GPS error is "
          f"mostly below ~{lc['unalign_dist_m']} m.", "",
          f"**4. Ambiguity.** If another route arc within +/-{lc['ambiguity_window']} positions is within {lc['ambiguity_margin_m']} m of the "
          "assigned one (typically a point on the node shared by consecutive arcs), the point is `ambiguous`: the assigned arc stays "
          "positive (1) and the alternatives are labelled -1 (ambiguous), not negative. Arcs with identical from/to nodes as the positive "
          "(duplicates) are also -1.", "",
          "**5. Route breaks.** The alignment does not require consecutive route arcs to be connected, so breaks do not stop it. Points "
          "aligned next to a break are flagged `near_route_break`.", "",
          "**6. Repeated arcs.** States are positions, not arc IDs, so each pass over a repeated arc is a separate state and order decides.", "",
          f"**7. Stationary points.** They usually stay at one position. A stationary point more than {lc['stationary_unalign_dist_m']} m from its "
          "aligned arc (e.g. parked off-road) is `unalignable` and all its candidates get -2.", "",
          "**8. Long gaps.** Positions may be skipped freely, so after a gap the alignment jumps ahead to wherever the GPS reappears. "
          "Skipped route arcs simply get no GPS points.", "",
          f"**9. Validation.** (a) Distance to the aligned arc; points beyond {lc['unalign_dist_m']} m are `unalignable`. (b) Agreement with the "
          "order-free nearest route arc. (c) Along-route progress speed: jumps of more than 200 m at more than 70 m/s are counted. "
          "(d) Share of route positions that received points. (e) Hard checks: positives equal `route[route_pos]`, at most one per point, "
          "none on unalignable points, route position never decreases.", ""]
    for part, o in all_obs.items():
        cd = all_cand[part]
        al = o[o.obs_status != "unalignable"]
        vc = cd.label.value_counts()
        pos, neg = vc.get(1, 0), vc.get(0, 0)
        lqp = lq[lq.partition == part]
        L += [f"**{part}:** positive {pos:,}, negative {neg:,}, ambiguous {vc.get(-1, 0):,}, unalignable-observation {vc.get(-2, 0):,} candidate rows. "
              f"Positive rate among labelled (1/0) rows {pos / max(pos + neg, 1):.2%}. Alignment distance median {al.align_dist_m.median():.1f} m, "
              f"95th percentile {al.align_dist_m.quantile(0.95):.1f} m. Agreement with order-free nearest route arc: "
              f"{(al.route_arc == al.naive_route_arc).mean():.2%}. Route positions receiving points: median {lqp.route_positions_hit_frac.median():.1%} per trip. "
              f"Progress jumps: {int(lqp.progress_jumps.sum())} in {int((lqp.progress_jumps > 0).sum())} trips.", ""]
    worst = lq.sort_values("unalignable_frac", ascending=False).head(8)
    L += ["Trips with the most unalignable points:", "", "| Partition | Trip | Points | Unalignable | Ambiguous | Stationary | Median dist (m) |",
          "|---|---|---|---|---|---|---|"]
    for _, r in worst.iterrows():
        L.append(f"| {r.partition} | {r.trip_id} | {r.n_obs:,} | {_pct(r.unalignable_frac)} | {_pct(r.ambiguous_frac)} | {_pct(r.stationary_frac)} | {r.median_align_dist_m:.1f} |")
    L += ["", f"Label warnings ({len(warnings)}): see `label_warnings.txt`.", ""]
    L += ["**10. Limitations.**", "",
          "- The reference route is not verified ground truth. If it is wrong, the labels are wrong too.",
          "- One aligned arc per GPS point. Near nodes, two arcs are equally correct; those cases are kept as -1, not resolved.",
          "- The alignment's parameters (sigma, cap, heading weight, thresholds) were set by reasoning about GPS noise, not tuned against an independent truth.",
          "- A point on a road parallel to the route, more than the cut-off away, is `unalignable` rather than negative.",
          "- Coverage misses (aligned arc not among candidates) leave an observation with no positive candidate. These are counted above.", ""]

    # ------------------------------------------------------------------ 7 checks
    L += ["## 7. Quality checks", "", "| Check | Result |", "|---|---|"]
    for k, v in checks.items():
        L.append(f"| {k} | {'PASS' if v else 'FAIL'} |")
    L += ["", "Per-trip results: `quality_checks.csv`.", ""]

    # ------------------------------------------------------------------ 8 outputs
    L += ["## 8. Outputs", "", "Datasets (`data/processed/`): " + ", ".join(f"`{k}` ({v} MB)" for k, v in meta["parquet_mb"].items()), "",
          "Reports: `trip_processing_report.csv`, `quality_checks.csv`, `candidate_coverage.csv`, `label_quality_per_trip.csv`, "
          "`label_warnings.txt`, `feature_stats_train.csv`, `feature_single_auc_train.csv`, `feature_schema.json`, `dataset_schema.json`, `phase2_summary.json`.", "",
          "Plots:"] + [f"- `{p}`" for p in plots] + ["", "Maps:"] + [f"- `maps/{m}`" for m in maps]
    L += ["", "## 9. Use in Phase 3", "",
          "Train on `candidates_train.parquet` rows with `label` in {0, 1}, features = `dataset_schema.json` -> `feature_columns`, "
          "groups = `trip_id` for GroupKFold. Rows with -1/-2 are excluded from fitting but kept for analysis. Top-1 accuracy is computed per "
          "observation over all its candidates. Student-test files are only used for evaluation.", ""]
    (out / "phase2_report.md").write_text("\n".join(L), encoding="utf-8")
