"""Writes results/phase3/phase3_report.md from the saved Phase 3 results (all numbers computed).

`rebuild_from_files(out_dir, cfg, artifacts_dir)` regenerates the report from the CSV/JSON files
without retraining (used by `python scripts\\train_phase3_models.py --report-only`).
"""
from __future__ import annotations
import json
from pathlib import Path
import numpy as np
import pandas as pd

from .modeling import MODEL_FAMILIES
from .features import FEATURE_SCHEMA

ORDER = ["baseline_nearest", "baseline_formula", "logistic_regression", "knn", "decision_tree", "random_forest", "hist_gradient_boosting"]
NAMES = {"baseline_nearest": "Nearest road (baseline)", "baseline_formula": "Distance + heading formula (baseline)",
         "logistic_regression": "Logistic Regression", "knn": "K-Nearest Neighbours", "decision_tree": "Decision Tree",
         "random_forest": "Random Forest", "hist_gradient_boosting": "Histogram Gradient Boosting"}


def _f(x, d=4):
    return "n/a" if x is None or (isinstance(x, float) and not np.isfinite(x)) else f"{x:.{d}f}"


def _pp(x):
    return f"{100 * x:+.2f} pp"


def _config_text(name, params, knn_rows):
    if name == "logistic_regression":
        return f"median impute + missing flags, standard scaling, L2 penalty C={params['C']}, lbfgs, max_iter={params['max_iter']}"
    if name == "knn":
        return f"impute + scaling, k={params['n_neighbors']}, {params['weights']} weights, Euclidean; trained on {knn_rows:,} sampled rows per fold"
    if name == "decision_tree":
        return f"impute, Gini, max_depth={params['max_depth']}, min_samples_leaf={params['min_samples_leaf']}"
    if name == "random_forest":
        return (f"impute, {params['n_estimators']} trees, max_depth={params['max_depth']}, min_samples_leaf={params['min_samples_leaf']}, "
                f"bootstrap {params['max_samples']:.0%} of rows per tree, sqrt(features) per split")
    if name == "hist_gradient_boosting":
        return (f"native NaN handling, {params['max_iter']} rounds, learning_rate={params['learning_rate']}, "
                f"max_leaf_nodes={params['max_leaf_nodes']}, log-loss, no early stopping")
    return ""


def write_report(out: Path, cfg, filt, folds, folds_df, summary, per_trip, selection, student, perm, coef, imp, red, exp, plots, meta):
    c3 = cfg["phase3"]
    S = summary.set_index("model").reindex([m for m in ORDER if m in set(summary.model)])
    sel = selection["selected"]
    nb = S.loc["baseline_nearest"]
    L = ["# PathSnap — Phase 3 Report: Baselines and Model Comparison", "",
         "_Generated by `scripts/train_phase3_models.py`. Every number comes from this run; nothing is typed in by hand._", "",
         f"Seed {exp['seed']}; Python {exp['python']}, scikit-learn {exp['sklearn']}; total run time {exp['elapsed_s'] / 60:.1f} min.", ""]

    # ---------------------------------------------------------------- 1 data
    L += ["## 1. Data and label filtering (train partition only)", "",
          "| Item | Rows | GPS points |", "|---|---|---|",
          f"| All candidate rows | {filt['rows_total']:,} | {filt['obs_total']:,} |",
          f"| Excluded: ambiguous (-1) | {filt['rows_excluded_ambiguous']:,} | {filt['obs_with_ambiguous_rows']:,} points contain such rows |",
          f"| Excluded: unalignable observation (-2) | {filt['rows_excluded_unalignable_observation']:,} | {filt['obs_with_unalignable_observation_rows']:,} |",
          f"| Excluded: invalid label | {filt['rows_excluded_invalid_label']:,} | |",
          f"| **Kept for fitting (labels 0/1)** | **{filt['rows_kept']:,}** ({filt['rows_kept_positive']:,} positive, {filt['rows_kept_negative']:,} negative; positive rate {filt['positive_rate']:.2%}) | {filt['obs_kept']:,} |",
          "", f"Ranking evaluation set (primary): {filt['obs_aligned_rankable']:,} aligned GPS points with exactly one positive candidate. "
          f"{filt['obs_aligned_without_positive']} aligned points whose correct arc was not among the candidates cannot be ranked and are excluded. "
          f"Secondary: {filt['obs_ambiguous_rankable']:,} ambiguous points, scored leniently (top candidate labelled 1 or -1 counts as correct).", "",
          "Ambiguous rows are excluded rather than relabelled as negatives: they are route arcs that are as close as the positive "
          "(usually the next arc at a junction), so calling them wrong would teach the model a contradiction.", ""]

    # ---------------------------------------------------------------- 2 features
    feats = exp["features"]
    L += ["## 2. Features", "", f"{len(feats)} features, taken from the Phase 2 schema (`phase3_feature_schema.json`): "
          + ", ".join(f"`{f}`" for f in feats) + ".", "",
          "Never given to a model (checked by `modeling.assert_no_leakage`): identifiers (`trip_id`, `seq`, `obs_idx`, `arc_id`, node IDs, `t`) "
          "which would allow memorising specific trips or roads, route-derived columns (`label`, `obs_status`, `route_pos`, `align_dist_m`) "
          "which reveal the answer, and information-only columns (absolute headings, search radii).", "",
          "Missing values (heading difference when the vehicle is not moving, first/last-point movement values) are imputed with the "
          "training-fold median, plus a 0/1 'was missing' column, inside each model pipeline; Histogram Gradient Boosting handles NaN natively. "
          "Observation-level features (speed, gaps, candidate count, ...) are identical for all candidates of a point, so on their own they "
          "cannot reorder candidates; they matter only through interactions (e.g. 'heading difference is informative only when moving'), "
          "which trees can learn and a linear model cannot.", ""]

    # ---------------------------------------------------------------- 3 validation
    L += ["## 3. Validation design", "",
          f"`StratifiedGroupKFold` with {c3['cv_folds']} folds, groups = `trip_id`, stratified on the label, shuffled with seed {exp['seed']}. "
          "All candidate rows of a trip are in the same fold, so the model is always scored on trips it has never seen; an assertion "
          "checks that training and validation trip sets are disjoint in every fold and that each trip is validated exactly once. "
          f"Five folds leave {min(f['n_val_trips'] for f in folds)}-{max(f['n_val_trips'] for f in folds)} trips per validation fold "
          "(enough variety per fold) and 64 for training, at an affordable cost of five fits per model.", "",
          "| Fold | Train trips | Val trips | Train rows | Val rows | Train positive rate | Val positive rate |", "|---|---|---|---|---|---|---|"]
    for f in folds:
        L.append(f"| {f['fold']} | {f['n_train_trips']} | {f['n_val_trips']} | {f['train_rows']:,} | {f['val_rows']:,} | {f['train_pos_rate']:.3f} | {f['val_pos_rate']:.3f} |")
    L += ["", "Trip lists per fold: `folds.json`. The student-test partition is not used for fitting, scaling, imputation, thresholds or selection.", ""]

    # ---------------------------------------------------------------- 4 models
    knn_rows = int(c3["knn_train_rows"])
    L += ["## 4. Baselines and models", "",
          "- **Nearest road**: pick the candidate with the smallest GPS-to-arc distance (`dist_rank` 0).",
          f"- **Distance + heading formula** (fixed, not tuned): score = -dist^2 / (2*{c3['baseline_formula']['sigma_m']}^2) - "
          f"{c3['baseline_formula']['w_heading']} * (1 - cos(heading difference)) / 2; heading term dropped when the heading is unreliable. "
          "Caution: this has the same form as the Phase 2 alignment cost, so it is not fully independent of how the labels were built.", "",
          "| Model | Family | Configuration (initial settings, not tuned) |", "|---|---|---|"]
    for m in ORDER[2:]:
        L.append(f"| {NAMES[m]} | {MODEL_FAMILIES[m]} | {_config_text(m, c3['models'][m], knn_rows)} |")
    L += ["", f"KNN is trained on a reproducible sample of whole GPS points (about {knn_rows:,} rows, drawn from each fold's training trips) because "
          "predicting with all ~1.2 million training rows would compare every validation row against every training row. It is still "
          "evaluated on the full validation folds, but it has **not** seen the same amount of training data as the other models.", "",
          f"No class weighting: within-point ranking does not depend on the overall positive rate, and Phase 7's HMM needs probabilities that "
          f"keep the real base rate. Threshold metrics use {c3['threshold']} (not tuned).", ""]

    # ---------------------------------------------------------------- 5 results
    L += ["## 5. Results (5-fold trip-grouped CV, mean ± standard deviation over folds)", "",
          "### 5a. GPS-point level: choosing the road (primary)", "",
          "| Model | Top-1 | Top-3 | Top-5 | MRR | Top-1 trip-macro | Worst trip Top-1 | Ambiguous points, lenient Top-1 |", "|---|---|---|---|---|---|---|---|"]
    for m, r in S.iterrows():
        star = " ★" if m == sel else ""
        L.append(f"| {NAMES[m]}{star} | {_f(r.top1_mean)} ± {_f(r.top1_std)} | {_f(r.top3_mean)} | {_f(r.top5_mean)} | {_f(r.mrr_mean)} | "
                 f"{_f(r.trip_macro_top1)} | {_f(r.trip_top1_min)} | {_f(r.amb_lenient_top1_mean)} |")
    L += ["", "Top-k = share of aligned GPS points whose correct arc is among the k highest-scored candidates of that point. "
          "MRR = mean of 1/rank of the correct arc. Trip-macro = average of per-trip Top-1, so long trips do not dominate.", "",
          "### 5b. Candidate level: classifying each candidate row (labels 0/1)", "",
          "| Model | Accuracy | Precision | Recall | F1 | Macro F1 | ROC-AUC | PR-AUC | Log loss |", "|---|---|---|---|---|---|---|---|---|"]
    for m, r in S.iterrows():
        L.append(f"| {NAMES[m]} | {_f(r.accuracy_mean)} | {_f(r.precision_mean)} | {_f(r.recall_mean)} | {_f(r.f1_mean)} ± {_f(r.f1_std)} | "
                 f"{_f(r.macro_f1_mean)} | {_f(r.roc_auc_mean)} | {_f(r.pr_auc_mean)} | {_f(r.log_loss_mean)} |")
    L += ["", f"For models, a candidate is predicted 'correct road' when its probability is >= {c3['threshold']}. Baselines produce a ranking, not a "
          "probability: their decision is 'the top candidate of each point', and log loss is not applicable (n/a). Accuracy is inflated by the "
          f"{1 - filt['positive_rate']:.0%} negatives (always answering 'wrong road' would score {1 - filt['positive_rate']:.3f}), so F1, PR-AUC and "
          "Top-1 are the informative numbers.", "",
          "### 5c. Runtime and size (this machine)", "",
          "| Model | Training rows per fold | Fit time per fold (s) | Predict time per 1,000 GPS points (s) | Final model size (MB) | Train Top-1 (sample) | Validation Top-1 | Gap |",
          "|---|---|---|---|---|---|---|---|"]
    tr_rows = folds_df.groupby("model").train_rows.mean()
    for m in ORDER[2:]:
        if m not in S.index:
            continue
        r = S.loc[m]
        gap = r.train_top1_mean - r.top1_mean
        L.append(f"| {NAMES[m]} | {tr_rows.get(m, np.nan):,.0f} | {_f(r.fit_s_mean, 1)} | {_f(r.predict_s_per_1k_obs_mean, 3)} | "
                 f"{_f(r.get('model_size_mb', np.nan), 3)} | {_f(r.train_top1_mean)} | {_f(r.top1_mean)} | {_pp(gap)} |")
    L += ["", "The train/validation gap is the over-fitting check: a large positive gap means the model learned patterns of the training trips "
          "that do not carry over to new trips.", ""]

    # ---------------------------------------------------------------- 6 selection
    tied = selection["tied_models"]
    L += ["## 6. Model selection", "", f"Rule (fixed in `config.yaml` before training): {selection['rule']}.", "",
          f"- Best mean CV Top-1: {selection['best_top1']:.4f}. Models within the tie margin: {', '.join(NAMES[t] for t in tied)}.",
          f"- **Selected: {NAMES[sel]}** — CV Top-1 {selection['selected_top1_mean']:.4f} ± {selection['selected_top1_std']:.4f}, "
          f"MRR {S.loc[sel, 'mrr_mean']:.4f}, F1 {S.loc[sel, 'f1_mean']:.4f}, PR-AUC {S.loc[sel, 'pr_auc_mean']:.4f}.",
          f"- Against the nearest-road baseline: Top-1 {_pp(selection['selected_top1_mean'] - selection['nearest_baseline_top1_mean'])} "
          f"({selection['nearest_baseline_top1_mean']:.4f} → {selection['selected_top1_mean']:.4f}); better in every fold: "
          f"{'yes' if selection['beats_baseline_in_every_fold'] else 'no'}.",
          f"- Against the distance+heading formula: Top-1 {_pp(S.loc[sel, 'top1_mean'] - S.loc['baseline_formula', 'top1_mean'])}.",
          f"- Decided at {selection['decided_at']} from cross-validation only; student-test was not used.", ""]
    others = [m for m in ORDER[2:] if m in S.index and m != sel]
    for m in others:
        d = S.loc[m, "top1_mean"] - S.loc[sel, "top1_mean"]
        L.append(f"- {NAMES[m]}: Top-1 {100 * d:+.3f} pp vs selected; fit {S.loc[m, 'fit_s_mean']:.1f} s/fold vs {S.loc[sel, 'fit_s_mean']:.1f} s; "
                 f"predict {S.loc[m, 'predict_s_per_1k_obs_mean']:.3f} vs {S.loc[sel, 'predict_s_per_1k_obs_mean']:.3f} s per 1,000 points.")
    fb = S.loc["baseline_formula"]
    d_formula = S.loc[sel, "top1_mean"] - fb.top1_mean
    L += ["", "### Honest assessment", ""]
    if abs(d_formula) < float(c3["selection"]["tie_margin"]):
        L += [f"- **On Top-1, the learned models do not clearly beat the hand-made distance+heading formula** ({fb.top1_mean:.4f} vs "
              f"{S.loc[sel, 'top1_mean']:.4f}, a difference of {_pp(d_formula)}, smaller than the fold-to-fold standard deviation of "
              f"{S.loc[sel, 'top1_std']:.4f}). Two reasons: (1) the labels come from a route alignment whose cost has the same form as "
              "this formula, so the formula is favoured by construction; (2) for a single GPS point, distance and heading carry most of "
              "the available information. The permutation importance below confirms that the models rely mostly on those two signals."]
    else:
        L += [f"- Against the hand-made distance+heading formula, the selected model's Top-1 differs by {_pp(d_formula)}."]
    L += [f"- Where the learned model does add value: it outputs **probabilities** (log loss {S.loc[sel, 'log_loss_mean']:.4f}; the formula "
          f"has none), ranks the correct arc in the top 3 more often ({S.loc[sel, 'top3_mean']:.4f} vs {fb.top3_mean:.4f}) and separates "
          f"correct from wrong candidates across all thresholds much better (PR-AUC {S.loc[sel, 'pr_auc_mean']:.4f} vs {fb.pr_auc_mean:.4f}). "
          "The HMM in Phase 7 uses the scores of all candidates, not only the top one, so these properties matter there.",
          f"- Models within the tie margin are practically equivalent on Top-1; the MRR tie-break chose {NAMES[sel]}. It also has the lowest "
          f"fold standard deviation ({S.loc[sel, 'top1_std']:.4f}) and the best worst-trip Top-1 ({S.loc[sel, 'trip_top1_min']:.4f}) among "
          f"the learned models in this run, a {S.loc[sel, 'model_size_mb']:.1f} MB file and fast prediction.",
          "- The candidate-level F1 of the baselines is not comparable with the models' F1: baselines are scored on 'top candidate of each "
          "point', models on 'probability >= threshold'."]
    if not selection["beats_nearest_baseline"]:
        L += ["", "**No model beats the nearest-road baseline on mean CV Top-1.** This must be investigated before Phase 4."]
    L += ["", f"Saved: `artifacts/phase3/selected_model.joblib` ({meta['size_mb']:.1f} MB, refitted on all 80 training trips in {meta['refit_s']:.1f} s) "
          "and `selected_model_meta.json` (feature order, parameters, versions).", ""]

    # ---------------------------------------------------------------- 7 feature analysis
    L += ["## 7. Feature analysis", "",
          f"**Permutation importance of the selected model** (drop in Top-1 when one feature is shuffled; each fold's model on "
          f"{c3['permutation_obs_per_fold']:,} of its held-out GPS points; computed after selection):", "",
          "| Feature | Top-1 drop (pp) mean ± sd |", "|---|---|"]
    for _, r in perm.iterrows():
        L.append(f"| `{r.feature}` | {100 * r.top1_drop_mean:.2f} ± {100 * r.top1_drop_std:.2f} |")
    small = perm[perm.top1_drop_mean.abs() < 0.001].feature.tolist()
    L += ["", f"Features whose shuffling changes Top-1 by less than 0.1 pp: {', '.join(f'`{s}`' for s in small) if small else 'none'}. "
          "A near-zero value does not prove a feature is useless: a correlated feature can take over its role (see redundancy below), and "
          "observation-level features can only act through interactions.", ""]
    if coef is not None:
        top = coef.head(8)
        L += ["**Logistic Regression coefficients** (standardised inputs; + raises the 'correct road' score). Largest by magnitude: "
              + ", ".join(f"`{r.feature}` {r.coef:+.2f}" for _, r in top.iterrows()) + ". "
              "Coefficients of correlated features can have surprising signs, because the model splits shared information between them.", ""]
    if imp is not None:
        for m, g in imp.groupby("model"):
            g = g.sort_values("importance", ascending=False).head(5)
            L.append(f"**Impurity importance, {NAMES[m]}** (top 5): " + ", ".join(f"`{r.feature}` {r.importance:.3f}" for _, r in g.iterrows())
                     + ". Impurity importance is computed on training data and favours continuous features; permutation importance on held-out trips is the more reliable measure.")
        L.append("")
    L += [f"**Redundancy** (|Spearman| >= 0.9 on training rows): " +
          (", ".join(f"`{r.feature_a}`-`{r.feature_b}` ({r.spearman:+.2f})" for _, r in red.iterrows()) if len(red) else "none") +
          ". Shuffling one feature of such a pair understates its importance because the other still carries the information.", "",
          "Feature importance describes what the model uses, not what causes a road to be correct.", ""]

    # ---------------------------------------------------------------- 8 student test
    if student is not None:
        st = student.set_index("model").reindex([m for m in ORDER if m in set(student.model)])
        L += ["## 8. Independent student-test check (not used for selection)", "",
              "Run once, after `model_selection.json` was written, with every model refitted on all 80 training trips. "
              "The official Models & Training guidelines and the report template ask for student-test results per model; these numbers "
              "did not influence any choice in this phase.", "",
              "| Model | Top-1 | Top-3 | MRR | F1 | Macro F1 | PR-AUC | Log loss |", "|---|---|---|---|---|---|---|---|"]
        for m, r in st.iterrows():
            L.append(f"| {NAMES[m]}{' ★' if m == sel else ''} | {_f(r.top1)} | {_f(r.top3)} | {_f(r.mrr)} | {_f(r.f1)} | {_f(r.macro_f1)} | {_f(r.pr_auc)} | {_f(r.log_loss)} |")
        L += ["", f"Student-test points ranked: {int(st.loc[sel, 'n_obs']):,} aligned GPS points in 10 trips.", ""]

    # ---------------------------------------------------------------- 9 limitations
    L += ["## 9. What this means and its limits", "",
          "- These are classifier-only predictions: each GPS point is decided on its own. Consecutive points can still be assigned to "
          "roads that are not connected; the HMM/Viterbi decoder (Phase 7) uses road connectivity to fix that.",
          "- Labels come from the Phase 2 route alignment. Scores measure agreement with that alignment, which treats the reference route as correct.",
          f"- Threshold metrics (precision, recall, F1) depend on the {c3['threshold']} threshold, which was not tuned; ranking metrics do not use a threshold.",
          "- All models use initial, untuned settings; KNN used a training subset. Phase 4 tunes the selected model.",
          "- Runtimes are from one machine and will differ on other laptops.", ""]

    # ---------------------------------------------------------------- 10 files
    L += ["## 10. Files", "",
          "`results/phase3/`: `cv_fold_metrics.csv` (every fold × model), `cv_summary.csv` (mean/sd/median), `per_trip_top1.csv`, "
          "`folds.json`, `label_filtering.json`, `model_selection.json`, `experiment_config.json`, `phase3_feature_schema.json`, "
          "`permutation_importance_selected.csv`, `logistic_regression_coefficients.csv`, `tree_impurity_importance.csv`, "
          "`feature_redundancy.csv`" + (", `student_test_metrics.csv`" if student is not None else "") + ".", "",
          "Plots:"] + [f"- `{p}`" for p in plots] + ["",
          "`data/processed/phase3_oof_scores.parquet`: out-of-fold scores of every model for every training candidate (each trip scored "
          "by a model that never saw it).", "`artifacts/phase3/`: `selected_model.joblib`, `selected_model_meta.json`.", ""]
    (out / "phase3_report.md").write_text("\n".join(L), encoding="utf-8")


def rebuild_from_files(out: Path, cfg, art: Path):
    """Regenerate the report from saved files (no retraining)."""
    filt = json.loads((out / "label_filtering.json").read_text(encoding="utf-8"))
    folds = json.loads((out / "folds.json").read_text(encoding="utf-8"))
    folds_df = pd.read_csv(out / "cv_fold_metrics.csv")
    summary = pd.read_csv(out / "cv_summary.csv")
    per_trip = pd.read_csv(out / "per_trip_top1.csv", index_col=0)
    selection = json.loads((out / "model_selection.json").read_text(encoding="utf-8"))
    st_path = out / "student_test_metrics.csv"
    student = pd.read_csv(st_path) if st_path.exists() else None
    perm = pd.read_csv(out / "permutation_importance_selected.csv")
    cp = out / "logistic_regression_coefficients.csv"
    coef = pd.read_csv(cp) if cp.exists() else None
    ip = out / "tree_impurity_importance.csv"
    imp = pd.read_csv(ip) if ip.exists() else None
    red = pd.read_csv(out / "feature_redundancy.csv")
    exp = json.loads((out / "experiment_config.json").read_text(encoding="utf-8"))
    meta = json.loads((art / "selected_model_meta.json").read_text(encoding="utf-8"))
    plots = sorted(p.name for p in out.glob("*.png"))
    write_report(out, cfg, filt, folds, folds_df, summary, per_trip, selection, student, perm, coef, imp, red, exp, plots, meta)
