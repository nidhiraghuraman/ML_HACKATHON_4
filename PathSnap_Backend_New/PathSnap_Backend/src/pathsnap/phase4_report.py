"""Writes results/phase4/phase4_report.md from the saved Phase 4 files (all numbers computed)."""
from __future__ import annotations
import json
from pathlib import Path
import numpy as np
import pandas as pd

WHY = {  # what each hyperparameter does and why this range
    "max_iter": "number of boosting rounds (trees): more rounds fit more detail, cost grows linearly",
    "learning_rate": "how strongly each new tree corrects the previous ones: small = careful but needs more rounds; log scale because the effect is multiplicative",
    "max_leaf_nodes": "size of each tree (number of leaves): more leaves = more feature interactions; log scale",
    "min_samples_leaf": "smallest group of candidates a leaf may describe: larger = smoother, less over-fitting; log scale",
    "l2_regularization": "penalty that shrinks leaf values; 0 = none (scikit-learn default)",
    "max_features": "share of features each split may consider: < 1 adds randomness (regularisation); 1.0 = all (default)",
    "n_estimators": "number of trees", "max_depth": "maximum tree depth", "max_samples": "share of rows per bootstrap sample",
    "C": "inverse regularisation strength; log scale", "n_neighbors": "how many similar training candidates vote; log scale",
}


def _f(x, d=4):
    return "n/a" if x is None or (isinstance(x, float) and not np.isfinite(x)) else f"{x:.{d}f}"


def rebuild_from_files(out: Path, art: Path, cfg: dict):
    c4 = cfg["phase4"]
    S = json.loads((out / "best_params.json").read_text(encoding="utf-8"))
    D = json.loads((out / "adoption_decision.json").read_text(encoding="utf-8"))
    FM = json.loads((art / "final_model.json").read_text(encoding="utf-8"))
    C = json.loads((out / "calibration.json").read_text(encoding="utf-8"))
    run = json.loads((out / "phase4_run.json").read_text(encoding="utf-8"))
    trials = pd.read_csv(out / "optuna_trials.csv")
    comp = pd.read_csv(out / "tuned_vs_untuned_folds.csv")
    slices = pd.read_csv(out / "error_slices.csv")
    worst = pd.read_csv(out / "worst_trips.csv")
    err = pd.read_csv(out / "error_points.csv", usecols=["error_type"])
    stp = out / "student_test_tuned_vs_untuned.csv"
    student = pd.read_csv(stp) if stp.exists() else None
    abp = out / "feature_ablation.json"
    abl = json.loads(abp.read_text(encoding="utf-8")) if abp.exists() else None
    name = S["model"]
    u, t = comp[comp.model == "untuned"].set_index("fold"), comp[comp.model == "tuned"].set_index("fold")

    L = ["# PathSnap — Phase 4 Report: Bayesian Hyperparameter Optimisation, Calibration and Error Analysis", "",
         "_Generated by `scripts/tune_phase4.py`. Every number comes from this run._" + (" **QUICK MODE: smoke test only, not results.**" if run["quick"] else ""), "",
         f"Model tuned: **{name}** (selected in Phase 3). Total run time {run['elapsed_min']:.1f} min; Python {run['python']}, "
         f"scikit-learn {run['sklearn']}, Optuna {S['optuna']}; seed {run['seed']}. Every decision used only the {run['trips']} training trips.", ""]

    L += ["## 1. Method", "",
          "**Why Bayesian optimisation.** Each trial trains and scores the model on several folds, so only tens of trials are affordable. "
          "Grid search would spend most of them in poor regions. Optuna's Tree-structured Parzen Estimator (TPE) learns from the trials so "
          "far where good and bad scores came from and proposes the next settings where good results are most likely: a sequential "
          "model-based (Bayesian) search.", "",
          f"**Objective.** Maximise mean Top-1 accuracy (aligned GPS points; candidates ranked within each point) over {len(S['tune_folds'])} "
          f"trip-grouped folds of a reproducible {S['tune_obs_fraction']:.0%} sample of whole GPS points from every training trip. Top-1 is the "
          "Phase 3 selection metric and what map matching needs; Macro F1, MRR and log loss are recorded for every trial too.", "",
          f"**Budget and pruning.** Up to {c4['n_trials']} trials (timeout {c4['timeout_minutes']} min). Trial 0 is the untuned Phase 3 setting, so "
          f"the search is measured against it. The next {c4['startup_trials']} trials are random (TPE needs examples). A median pruner stops a "
          "trial after a fold if its running mean is below the median of earlier trials at that fold.", "",
          "**Search space:**", "", "| Hyperparameter | Range | Scale | Untuned value | What it controls |", "|---|---|---|---|---|"]
    for p, s in S["search_space"].items():
        rng = f"{s['low']} - {s['high']}" + (f" (step {s['step']})" if "step" in s else "")
        L.append(f"| `{p}` | {rng} | {'log' if s.get('log') else 'linear'} | {S['untuned_params'].get(p)} | {WHY.get(p, '')} |")
    fixed = {k: v for k, v in S["untuned_params"].items() if k not in S["search_space"]}
    L += ["", f"Fixed (not searched): {fixed}. Ranges are centred on scikit-learn's defaults and widened in both directions by roughly a "
          f"factor that a {c4['n_trials']}-trial search can still cover.", ""]

    done = trials[trials.state == "COMPLETE"]
    L += ["## 2. Search results", "",
          f"{S['n_trials_run']} trials in {S['search_minutes']:.1f} min: {S['completed']} completed, {S['pruned']} pruned. "
          f"Untuned settings (trial 0): Top-1 {_f(S['untuned_value_top1'])}. Best: trial {S['best_trial']}, Top-1 {S['best_value_top1']:.4f} "
          f"({100 * (S['best_value_top1'] - (S['untuned_value_top1'] or np.nan)):+.2f} pp on the search folds).", "",
          "| Hyperparameter | Untuned | Best found |", "|---|---|---|"]
    for p in S["search_space"]:
        bv = S["best_params"][p]
        L.append(f"| `{p}` | {S['untuned_params'].get(p)} | {round(bv, 4) if isinstance(bv, float) else bv} |")
    top = done.sort_values("value_top1", ascending=False).head(5)
    L += ["", "Top 5 completed trials (search folds):", "", "| Trial | Top-1 | MRR | Macro F1 | Log loss | Fit s/fold |", "|---|---|---|---|---|---|"]
    for _, r in top.iterrows():
        L.append(f"| {int(r.trial)} | {r.value_top1:.4f} | {_f(r.get('mrr'))} | {_f(r.get('macro_f1'))} | {_f(r.get('log_loss'))} | {_f(r.get('fit_s'), 1)} |")
    spread = done.value_top1.max() - done.value_top1.min() if len(done) else np.nan
    L += ["", f"Spread of completed-trial Top-1: {100 * spread:.2f} pp. Full history: `optuna_trials.csv`.", ""]

    L += [f"## 3. Tuned vs untuned (same {len(u)} trip-grouped folds as Phase 3, all training data)", "",
          "| Metric | Untuned (mean ± sd) | Tuned (mean ± sd) | Difference |", "|---|---|---|---|"]
    for m, lab, better in [("top1", "Top-1", "higher"), ("macro_f1", "Macro F1", "higher"), ("mrr", "MRR", "higher"),
                           ("pr_auc", "PR-AUC", "higher"), ("log_loss", "Log loss", "lower"), ("predict_s_per_1k_obs", "Predict s / 1,000 GPS points", "lower")]:
        if m in u and m in t:
            L.append(f"| {lab} ({better} is better) | {u[m].mean():.4f} ± {u[m].std():.4f} | {t[m].mean():.4f} ± {t[m].std():.4f} | {t[m].mean() - u[m].mean():+.4f} |")
    L += ["", "Top-1 per fold (untuned → tuned): " + "; ".join(f"fold {f}: {u.loc[f, 'top1']:.4f} → {t.loc[f, 'top1']:.4f}" for f in u.index) + ".", "",
          f"**Decision (rule fixed in config: {D['rule']}).** Mean CV Top-1 {D['untuned_cv_top1']:.4f} → {D['tuned_cv_top1']:.4f} "
          f"({D['difference_pp']:+.2f} pp; better in {D['folds_improved']} of {D['n_folds']} folds). "
          + ("**The tuned settings are adopted.**" if D["adopted"] else "**The tuned settings are not adopted; the Phase 3 model stays the final model.**"), "",
          f"Final model for Phases 5-6: `{FM['path']}` ({FM['source']}); settings {FM['params']}; {FM['size_mb']:.2f} MB; "
          f"reloaded and checked identical: {FM['reload_check_identical']}. Pointer file: `artifacts/phase4/final_model.json`.", ""]
    if abs(D["difference_pp"]) < 100 * max(u.top1.std(), 1e-9):
        L += [f"The Top-1 change ({D['difference_pp']:+.2f} pp) is smaller than the fold-to-fold standard deviation ({100 * u.top1.std():.2f} pp), "
              "so tuning makes at most a small difference for this model on this data.", ""]

    if student is not None:
        L += ["## 4. Independent student-test check (not used for any decision)", "",
              "| Model | Top-1 | Top-3 | MRR | Macro F1 | PR-AUC | Log loss | Predict s / 1,000 points |", "|---|---|---|---|---|---|---|---|"]
        for _, r in student.iterrows():
            L.append(f"| {r.model} | {r.top1:.4f} | {r.top3:.4f} | {r.mrr:.4f} | {r.macro_f1:.4f} | {r.pr_auc:.4f} | {r.log_loss:.4f} | {r.predict_s_per_1k_obs:.3f} |")
        L += ["", "Computed after the adoption decision was saved. 10 trips only, so differences of a few tenths of a point are within noise.", ""]

    fin = C["final"]
    L += ["## 5. Probability calibration (out-of-fold, candidates with label 0/1)", "",
          "| Model | ECE | Brier score | Log loss |", "|---|---|---|---|"]
    for k in ("untuned", "tuned"):
        if k in C:
            L.append(f"| {k} | {C[k]['ece']:.4f} | {C[k]['brier']:.4f} | {C[k]['log_loss']:.4f} |")
    L += ["", f"ECE = average gap between predicted probability and observed frequency (0 = perfectly honest). Recalibration threshold: "
          f"{C['ece_threshold']}. Final model ({fin}): ECE {C[fin]['ece']:.4f} → "
          + ("**recalibration recommended before the HMM.**" if C["recalibration_recommended"] else "**no recalibration needed**; the probabilities can be used directly as HMM emission scores.")
          + " Reliability tables: `reliability_*.csv`.", ""]

    vc = err.error_type.value_counts()
    nw = int((err.error_type != "correct").sum())
    L += ["## 6. Error analysis (final model, out-of-fold, aligned GPS points)", "",
          f"{nw:,} of {len(err):,} points have a wrong Top-1 ({nw / len(err):.2%}).", "",
          "| Error type | Points | Share of errors | Meaning |", "|---|---|---|---|",
          f"| wrong direction | {vc.get('reverse_direction', 0):,} | {vc.get('reverse_direction', 0) / max(nw, 1):.1%} | opposite arc of the same two-way street |",
          f"| neighbouring arc | {vc.get('adjacent_arc', 0):,} | {vc.get('adjacent_arc', 0) / max(nw, 1):.1%} | shares a node with the correct arc (junction / next segment) |",
          f"| different road | {vc.get('other_road', 0):,} | {vc.get('other_road', 0) / max(nw, 1):.1%} | e.g. a parallel street |", "",
          "Error rate by condition (largest differences from the overall rate first):", "",
          "| Condition | Group | Points | Top-1 error rate | Share of all errors |", "|---|---|---|---|---|"]
    overall = slices[slices.slice == "all points"].top1_error_rate.iat[0]
    s2 = slices[slices.slice != "all points"].assign(gap=lambda d: (d.top1_error_rate - overall).abs()).sort_values("gap", ascending=False)
    for _, r in s2.head(14).iterrows():
        L.append(f"| {r.slice} | {r.group} | {r.points:,} | {r.top1_error_rate:.2%} | {r.share_of_all_errors:.1%} |")
    L += ["", f"Overall error rate {overall:.2%}. Full table: `error_slices.csv`; per point: `error_points.csv`.", "",
          "Worst trips (Top-1 error rate):", "", "| Trip | Points | Error rate |", "|---|---|---|"]
    for _, r in worst.head(6).iterrows():
        L.append(f"| {r.trip_id} | {int(r.points):,} | {r.top1_error_rate:.2%} |")
    L += ["", "Implication for Phase 5: neighbouring-arc and wrong-direction errors are the cases where the previous and next GPS points "
          "help (a vehicle cannot jump to the opposite carriageway or skip back along a road), so HMM/Viterbi decoding is expected to "
          "fix part of them; whether it does is measured in Phase 5.", ""]

    if abl:
        L += ["## 7. Feature ablation (analysis only)", "",
              f"Dropping the {len(abl['dropped'])} features whose Phase 3 permutation importance was below {100 * c4['ablation_threshold']:.1f} pp "
              f"({', '.join('`' + d + '`' for d in abl['dropped'])}) changes mean CV Top-1 from {abl['full_cv_top1']:.4f} to {abl['reduced_cv_top1']:.4f} "
              f"({100 * (abl['reduced_cv_top1'] - abl['full_cv_top1']):+.2f} pp) and Macro F1 from {abl['full_cv_macro_f1']:.4f} to {abl['reduced_cv_macro_f1']:.4f}. "
              "The final model keeps all features so later phases use one feature schema.", ""]

    L += ["## 8. Limitations", "",
          f"- The search ran on {S['tune_obs_fraction']:.0%} of GPS points with {len(S['tune_folds'])} folds to fit the time budget; the adoption "
          "decision uses all data and the Phase 3 folds, so it does not rely on the subset.",
          f"- {S['n_trials_run']} trials explore a {len(S['search_space'])}-dimensional space only coarsely.",
          "- The objective is Top-1 against the Phase 2 route-alignment labels and inherits their limitations.",
          "- Runtimes are from one machine.", "",
          "## 9. Files", "",
          "`results/phase4/`: `optuna_trials.csv`, `best_params.json`, `tuned_vs_untuned_folds.csv`, `adoption_decision.json`, "
          "`calibration.json`, `reliability_*.csv`, `error_points.csv`, `error_slices.csv`, `worst_trips.csv`"
          + (", `student_test_tuned_vs_untuned.csv`" if student is not None else "") + (", `feature_ablation.json`" if abl else "")
          + ", `phase4_run.json`; plots: " + ", ".join(f"`{p}`" for p in run["plots"]) + ".", "",
          "`artifacts/phase4/final_model.json` (+ `tuned_model.joblib` if the tuned settings were adopted).", ""]
    (out / "phase4_report.md").write_text("\n".join(L), encoding="utf-8")
